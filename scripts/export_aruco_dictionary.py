"""Regenerate the bundled OpenCV dictionary and independent test fixtures (requires cv2)."""
import base64
import json
from pathlib import Path
import cv2
import numpy as np

root = Path(__file__).resolve().parents[1]
dictionary = cv2.aruco.getPredefinedDictionary(cv2.aruco.DICT_4X4_1000)
codes = []
for marker_id in range(1000):
    bits = cv2.aruco.generateImageMarker(dictionary, marker_id, 6)[1:5, 1:5]
    codes.append(int(''.join(str(int(bit > 0)) for bit in bits.flat), 2))
(root / 'src/data/aruco4x4.js').write_text('// OpenCV DICT_4X4_1000, generated by scripts/export_aruco_dictionary.py.\nexport default ' + json.dumps(codes) + ';\n')
fixtures = []
for marker_id in (0, 7, 49, 50, 123, 999):
    marker = cv2.aruco.generateImageMarker(dictionary, marker_id, 180)
    image = np.full((260, 260), 255, dtype=np.uint8)
    image[40:220, 40:220] = marker
    fixtures.append({'id': marker_id, 'width': 260, 'height': 260, 'gray': base64.b64encode(image.tobytes()).decode()})
# Camera-like perspective, blur, and uneven lighting samples.
marker = cv2.aruco.generateImageMarker(dictionary, 7, 180)
image = np.full((260, 260), 255, dtype=np.uint8)
image[40:220, 40:220] = marker
transform = cv2.getPerspectiveTransform(np.float32([[40,40],[219,40],[219,219],[40,219]]), np.float32([[55,35],[225,60],[205,230],[30,200]]))
perspective = cv2.warpPerspective(image, transform, (260,260), borderValue=255)
blurred = cv2.GaussianBlur(perspective, (3,3), 0.8)
lighting = np.linspace(0.65, 1.0, 260)[None, :]
for label, sample in [('perspective', perspective), ('blur-lighting', (blurred * lighting).astype(np.uint8))]:
    fixtures.append({'id': 7, 'sample': label, 'width': 260, 'height': 260, 'gray': base64.b64encode(sample.tobytes()).decode()})
(root / 'tests/fixtures/opencv-markers.json').write_text(json.dumps(fixtures, separators=(',', ':')))
